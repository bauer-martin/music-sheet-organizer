export const dataSet: Map<MusicSheetFolderModel['key'], MusicSheetFolderModel> = Object.entries(rawDataSet).reduce(
    (acc, [folderTitle, sheetTitles]) => {
        const folderKey = generateUuid()
        acc.set(folderKey, {
            key: folderKey,
            title: folderTitle,
            sheets: sheetTitles.map(sheetTitle => ({ key: generateUuid(), title: sheetTitle })),
        })
        return acc
    },
    new Map<MusicSheetFolderModel['key'], MusicSheetFolderModel>()
)
